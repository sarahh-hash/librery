-- Связи книг и авторов
insert into book_authors (book_isbn, author_id)
select v.isbn, a.id
from (values
          ('9785446109149', 'Джошуа Блох'),
          ('9785170906302', 'Л. Н. Толстой'),
          ('9785446109606', 'Роберт Мартин'),
          ('9785446111012', 'Кей Хорстманн'),
          ('9785446111012', 'Гари Корнелл')
     ) as v(isbn, name)
         join authors a on a.name = v.name;

